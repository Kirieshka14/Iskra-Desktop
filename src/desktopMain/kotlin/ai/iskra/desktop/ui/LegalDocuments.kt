@Composable
fun LegalDocumentDialog(
    initialTab: LegalDocType = LegalDocType.PRIVACY,
    onDismiss: () -> Unit
) {
    var activeTab by remember { mutableStateOf(initialTab) }
    val scrollState = rememberScrollState()

    LaunchedEffect(activeTab) {
        scrollState.scrollTo(0)
    }

    Dialog(
        onDismissRequest = onDismiss,
        properties = DialogProperties(usePlatformDefaultWidth = false)
    ) {
        Column(
            modifier = Modifier
                .widthIn(max = 680.dp)
                .fillMaxWidth(0.92f)
                .fillMaxHeight(0.86f)
                .clip(RoundedCornerShape(20.dp))
                .background(IskraColors.surface)
                .border(1.dp, IskraColors.borderStrong, RoundedCornerShape(20.dp))
                .padding(20.dp),
            verticalArrangement = Arrangement.spacedBy(12.dp)
        ) {
            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Column(verticalArrangement = Arrangement.spacedBy(2.dp)) {
                    Text(
                        text = "Правовая информация IskraAi",
                        fontSize = 17.sp,
                        fontWeight = FontWeight.Bold,
                        color = IskraColors.text
                    )
                    Text(
                        text = "В соответствии с ФЗ № 152-ФЗ, ФЗ № 149-ФЗ и ФЗ № 436-ФЗ (18+)",
                        fontSize = 11.sp,
                        color = IskraColors.muted
                    )
                }

                Box(
                    modifier = Modifier
                        .clip(RoundedCornerShape(8.dp))
                        .background(IskraColors.surface2)
                        .clickable { onDismiss() }
                        .padding(horizontal = 10.dp, vertical = 5.dp)
                ) {
                    Text("✕ Закрыть", fontSize = 12.sp, color = IskraColors.text, fontWeight = FontWeight.SemiBold)
                }
            }

            Row(
                modifier = Modifier
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(12.dp))
                    .background(IskraColors.surface2)
                    .border(1.dp, IskraColors.border, RoundedCornerShape(12.dp))
                    .padding(4.dp),
                horizontalArrangement = Arrangement.spacedBy(4.dp)
            ) {
                listOf(
                    LegalDocType.PRIVACY to "Политика конфиденциальности",
                    LegalDocType.TERMS to "Пользовательское соглашение"
                ).forEach { (type, label) ->
                    val selected = activeTab == type
                    Box(
                        modifier = Modifier
                            .weight(1f)
                            .clip(RoundedCornerShape(9.dp))
                            .background(if (selected) IskraColors.text else androidx.compose.ui.graphics.Color.Transparent)
                            .clickable { activeTab = type }
                            .padding(vertical = 8.dp),
                        contentAlignment = Alignment.Center
                    ) {
                        Text(
                            text = label,
                            fontSize = 12.sp,
                            fontWeight = FontWeight.Bold,
                            color = if (selected) IskraColors.canvas else IskraColors.muted
                        )
                    }
                }
            }

            Column(
                modifier = Modifier
                    .weight(1f)
                    .fillMaxWidth()
                    .clip(RoundedCornerShape(14.dp))
                    .background(IskraColors.canvas)
                    .border(1.dp, IskraColors.border, RoundedCornerShape(14.dp))
                    .verticalScroll(scrollState)
                    .padding(18.dp),
                verticalArrangement = Arrangement.spacedBy(14.dp)
            ) {
                Text(
                    text = if (activeTab == LegalDocType.PRIVACY)
                        "Политика конфиденциальности и обработки персональных данных IskraAi"
                    else
                        "Пользовательское соглашение (Условия использования) IskraAi",
                    fontSize = 16.sp,
                    fontWeight = FontWeight.Bold,
                    color = IskraColors.text
                )
                Text(
                    text = "Действующая редакция • Возрастное ограничение: Строго 18+",
                    fontSize = 11.sp,
                    color = IskraColors.subtle
                )

                val sections = if (activeTab == LegalDocType.PRIVACY) PRIVACY_POLICY_SECTIONS else TERMS_OF_SERVICE_SECTIONS
                sections.forEach { sec ->
                    Column(verticalArrangement = Arrangement.spacedBy(6.dp)) {
                        Text(
                            text = sec.title,
                            fontSize = 14.sp,
                            fontWeight = FontWeight.Bold,
                            color = IskraColors.text
                        )
                        sec.paragraphs.forEach { p ->
                            Text(
                                text = p,
                                fontSize = 12.sp,
                                lineHeight = 18.sp,
                                color = IskraColors.muted
                            )
                        }
                    }
                }
            }

            Row(
                modifier = Modifier.fillMaxWidth(),
                horizontalArrangement = Arrangement.SpaceBetween,
                verticalAlignment = Alignment.CenterVertically
            ) {
                Text(
                    text = "© 2026 IskraAi • Возрастное ограничение 18+",
                    fontSize = 11.sp,
                    color = IskraColors.subtle
                )
                Button(
                    onClick = onDismiss,
                    shape = RoundedCornerShape(10.dp),
                    colors = ButtonDefaults.buttonColors(
                        containerColor = IskraColors.accent,
                        contentColor = IskraColors.accentInk
                    ),
                    contentPadding = PaddingValues(horizontal = 20.dp, vertical = 8.dp)
                ) {
                    Text("Понятно", fontSize = 13.sp, fontWeight = FontWeight.Bold)
                }
            }
        }
    }
}
